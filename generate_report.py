import json
from pathlib import Path
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors

def main():
    metrics_path = Path("artifacts/metrics.json")
    metrics = json.loads(metrics_path.read_text()) if metrics_path.exists() else {}
    out = Path("assignment_report.pdf")
    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(out), pagesize=A4, rightMargin=45, leftMargin=45, topMargin=45, bottomMargin=45)
    story = [
        Paragraph("ML Model Deployment Strategies and Model Serving using FastAPI", styles["Title"]),
        Spacer(1, 12),
        Paragraph("Dataset: Titanic – Machine Learning from Disaster (Kaggle), train.csv.", styles["BodyText"]),
        Spacer(1, 8),
        Paragraph("Implementation summary", styles["Heading2"]),
        Paragraph("A Random Forest classification pipeline is trained once on a stratified training split. Missing numeric values are imputed with medians, missing categorical values with the most frequent category, and categorical values are one-hot encoded. The fitted preprocessing and classifier are saved together as artifacts/model.pkl and reused for all inference approaches and API serving.", styles["BodyText"]),
        Spacer(1, 10),
        Paragraph("Training and evaluation", styles["Heading2"]),
    ]
    rows = [["Item", "Result"],
            ["Model", metrics.get("model_name", "Generated by running model.py")],
            ["Dataset rows", str(metrics.get("dataset_rows", "Run model.py to calculate"))],
            ["Training rows", str(metrics.get("training_rows", "Run model.py to calculate"))],
            ["Testing rows", str(metrics.get("testing_rows", "Run model.py to calculate"))],
            ["Hold-out accuracy", f'{metrics.get("accuracy_percent", "Calculated when run")}%']]
    table = Table(rows, colWidths=[150, 300])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#24476B")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("PADDING", (0,0), (-1,-1), 7),
    ]))
    story.extend([table, Spacer(1, 12), Paragraph("Observations", styles["Heading2"])])
    observations = [
        ("1. Online vs Batch Inference", "Online inference predicts one record at a time and returns an immediate result. Batch inference predicts many records together, which is efficient for larger offline jobs."),
        ("2. Streaming vs Batch Inference", "Streaming inference handles incoming records sequentially as they arrive, here with a one-second delay. Batch inference collects a group of records and predicts them in one call."),
        ("3. Why FastAPI?", "FastAPI exposes the model through HTTP REST endpoints, validates request bodies with Pydantic, generates interactive Swagger documentation at /docs, and supports straightforward integration with other applications."),
        ("4. Why reuse the same trained model?", "Reusing one saved pipeline keeps preprocessing and model parameters consistent across online, batch, streaming, and API predictions. Retraining separate models could produce inconsistent results and makes comparison less reliable.")
    ]
    for title, body in observations:
        story.extend([Paragraph(title, styles["Heading3"]), Paragraph(body, styles["BodyText"]), Spacer(1, 7)])
    story.extend([Spacer(1, 8), Paragraph("Run the project with the instructions in README.md. Accuracy and row counts are filled from the actual dataset when model.py is run.", styles["Italic"])])
    doc.build(story)
    print(f"Created {out}")

if __name__ == "__main__":
    main()
